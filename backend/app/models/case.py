"""
Court Vision AI — SQLAlchemy Models: Case
"""
import uuid
import enum
from datetime import datetime, timezone
from sqlalchemy import String, Text, DateTime, ForeignKey, Enum as SAEnum, JSON
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.core.database import Base


class CaseType(str, enum.Enum):
    CRIMINAL = "criminal"
    CIVIL = "civil"
    CONSTITUTIONAL = "constitutional"
    CORPORATE = "corporate"
    FAMILY = "family"
    INTELLECTUAL_PROPERTY = "intellectual_property"
    LABOUR = "labour"
    TAX = "tax"
    OTHER = "other"


class CaseStatus(str, enum.Enum):
    PREPARING = "preparing"
    ACTIVE = "active"
    ARCHIVED = "archived"
    CLOSED = "closed"


class UserCaseRole(str, enum.Enum):
    DEFENCE = "defence"
    PROSECUTION = "prosecution"
    RESEARCHER = "researcher"
    STUDENT = "student"


class Case(Base):
    __tablename__ = "cases"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    owner_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    name: Mapped[str] = mapped_column(String(500), nullable=False)
    case_type: Mapped[CaseType] = mapped_column(
        SAEnum(CaseType, name="case_type"), nullable=False
    )
    description: Mapped[str | None] = mapped_column(Text, nullable=True)
    case_number: Mapped[str | None] = mapped_column(String(100), nullable=True)
    user_role: Mapped[UserCaseRole] = mapped_column(
        SAEnum(UserCaseRole, name="user_case_role"), nullable=False, default=UserCaseRole.RESEARCHER
    )
    status: Mapped[CaseStatus] = mapped_column(
        SAEnum(CaseStatus, name="case_status"), default=CaseStatus.PREPARING, nullable=False
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )
    # Cached evidence graph JSON (generated by Groq, invalidated on refresh)
    evidence_graph: Mapped[dict | None] = mapped_column(JSON, nullable=True, default=None)

    # Relationships
    owner: Mapped["User"] = relationship("User", back_populates="cases")
    documents: Mapped[list["Document"]] = relationship(
        "Document", back_populates="case", cascade="all, delete-orphan"
    )
    members: Mapped[list["CaseMember"]] = relationship(
        "CaseMember", back_populates="case", cascade="all, delete-orphan"
    )
    audit_logs: Mapped[list["AuditLog"]] = relationship("AuditLog", back_populates="case")


class CaseMember(Base):
    __tablename__ = "case_members"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    case_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("cases.id", ondelete="CASCADE"), nullable=False, index=True
    )
    user_id: Mapped[str] = mapped_column(
        String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True
    )
    role: Mapped[str] = mapped_column(String(50), nullable=False, default="viewer")
    joined_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False
    )
    case: Mapped["Case"] = relationship("Case", back_populates="members")
